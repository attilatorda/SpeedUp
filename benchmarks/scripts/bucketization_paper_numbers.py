#!/usr/bin/env python3
"""Writes the tables and number macros of the Bucketization paper
(docs/papers/bucketization/generated/) from the CSVs in benchmarks/outputs/.

Machines:
  linux    the reference runs (4-vCPU Xeon container), untagged CSV names
  windows  the Ryzen 5 2600X re-run, CSVs tagged _windows_ryzen2600x
"""
import csv
import importlib.util
import os
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUTS = ROOT / "benchmarks" / "outputs"
GEN = ROOT / "docs" / "papers" / "bucketization" / "generated"
TAG = "windows_ryzen2600x"
MACHINES = {"linux": "", "windows": "_" + TAG}


def load_runner():
    spec = importlib.util.spec_from_file_location("runner", ROOT / "benchmarks" / "scripts" /
                                                  "run_bucketization_benchmarks.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def tables(path):
    """Every table of a CSV; the Dolphin CSV has a second ('open') table after a blank line."""
    if not path.exists():
        return []
    with open(path) as f:  # universal newlines: the checkout may have CRLF
        chunks = f.read().split("\n\n")
    return [list(csv.DictReader(c.strip().splitlines())) for c in chunks if c.strip()]


def rows(path):
    t = tables(path)
    return t[0] if t else []


def num(v):
    """Milliseconds as text: three significant figures, at least one decimal below 10."""
    if v >= 100:
        return f"{v:,.0f}".replace(",", "{,}")
    if v >= 10:
        return f"{v:.0f}"
    if v >= 1:
        return f"{v:.1f}"
    if v >= 0.1:
        return f"{v:.2f}"
    if v >= 0.01:
        return f"{v:.3f}"
    return f"{v:.4f}"


def factor(v):
    return f"{v:,.0f}".replace(",", "{,}") if v >= 10 else f"{v:.1f}"


def rng(values, fmt=num):
    lo, hi = min(values), max(values)
    return fmt(lo) if fmt(lo) == fmt(hi) else f"{fmt(lo)}--{fmt(hi)}"


class Macros:
    def __init__(self):
        self.lines = ["% Generated by benchmarks/scripts/bucketization_paper_numbers.py. Do not edit.",
                      "\\makeatletter"]

    def define(self, key, value):
        self.lines.append(f"\\expandafter\\def\\csname bz@{key}\\endcsname{{{value}}}")

    def text(self):
        return "\n".join(self.lines + [
            "\\newcommand{\\bz}[1]{\\@ifundefined{bz@#1}{\\textbf{??}}{\\csname bz@#1\\endcsname}}",
            "\\makeatother"]) + "\n"


def synthetic(m, machine):
    """Synthetic micro-benchmark: results_bucketization_<machine>.csv."""
    path = OUTPUTS / ("results_bucketization_linux.csv" if machine == "linux"
                      else f"results_bucketization_{TAG}.csv")
    data = rows(path)
    if not data:
        return None
    for r in data:
        base = f"syn@{machine}@{r['n']}@{r['key']}"
        for col in ("std_sort_ms", "presort_ms", "switch_first_page_ms", "cached_switch_ms", "switch_sort_all_ms"):
            m.define(f"{base}@{col}", num(float(r[col])))
        m.define(f"{base}@speedup", factor(float(r["std_sort_ms"]) / float(r["switch_first_page_ms"])))
    return data


def synthetic_table(data_by_machine):
    out = ["\\begin{tabular}{llrrrrrr}", "\\toprule",
           "Machine & Key & \\texttt{std::sort} & Pre-sort & Switch + page & Speed-up & Cached switch & "
           "Switch + sort all\\\\",
           "\\midrule"]
    names = {"linux": "Xeon (Linux)", "windows": "Ryzen (Windows)"}
    for machine, data in data_by_machine.items():
        if not data:
            continue
        big = [r for r in data if r["n"] == "1000000"]
        for i, r in enumerate(big):
            label = names[machine] if i == 0 else ""
            presort = num(float(r["presort_ms"]))
            s = float(r["std_sort_ms"])
            f = float(r["switch_first_page_ms"])
            out.append(f"{label} & {r['key']} & {num(s)} & {presort} & {num(f)} & {factor(s / f)}$\\times$ & "
                       f"{num(float(r['cached_switch_ms']))} & {num(float(r['switch_sort_all_ms']))}\\\\")
        out.append("\\midrule")
    out[-1] = "\\bottomrule"
    out.append("\\end{tabular}")
    return "\n".join(out) + "\n"


def summary(runner, m, machine):
    """Per-project summary on the large real listings, as in cross-project-benchmarks.md."""
    if machine != "linux":
        runner.apply_tag(TAG)
    out = []
    for label, resort, switch, ratio, presort, valid, total, slower, cases in runner.summary_rows():
        out.append((label, resort, switch, ratio, presort, valid, total, slower, cases))
    # Dolphin is measured by its own benchmark; same columns.
    dolphin = rows(Path(runner.DOLPHIN_CSV))
    if dolphin:
        large = [r for r in dolphin if r["dataset"] in runner.LARGE]
        resort = [float(r["dolphin_resort_ms"]) for r in large]
        switch = [float(r["keyed_switch_ms"]) for r in large]
        presort = [float(r["keyed_presort_ms"]) for r in large]
        ratio = [a / b for a, b in zip(resort, switch)]
        valid = sum(r["order_ok"] == "1" or r["dolphin_comparator_consistent"] == "0" for r in dolphin)
        slower = sum(p + s > t for p, s, t in zip(presort, switch, resort))
        out.insert(0, ("Dolphin", resort, switch, ratio, presort, valid, len(dolphin), slower, len(large)))
    for label, resort, switch, ratio, presort, valid, total, slower, cases in out:
        key = label.split(" ")[0].lower()
        if "native" in label:
            key += "native"
        m.define(f"sum@{machine}@{key}@resort", rng(resort))
        m.define(f"sum@{machine}@{key}@switch", rng(switch))
        m.define(f"sum@{machine}@{key}@speedup", rng([max(r, 1) for r in ratio], factor))
        m.define(f"sum@{machine}@{key}@presort", rng(presort))
        m.define(f"sum@{machine}@{key}@valid", f"{valid}/{total}")
        m.define(f"sum@{machine}@{key}@invalid", str(total - valid))
        m.define(f"sum@{machine}@{key}@slower", str(slower))
    if out:
        all_ratio = [r for row in out for r in row[3]]
        all_switch = [s for row in out for s in row[2]]
        all_resort = [s for row in out for s in row[1]]
        all_presort = [s for row in out for s in row[4]]
        m.define(f"sum@{machine}@all@speedup", rng([max(r, 1) for r in all_ratio], factor))
        m.define(f"sum@{machine}@all@speedupmedian", factor(statistics.median(all_ratio)))
        m.define(f"sum@{machine}@all@switch", rng(all_switch))
        m.define(f"sum@{machine}@all@resort", rng(all_resort))
        m.define(f"sum@{machine}@all@presortmedian", num(statistics.median(all_presort)))
        m.define(f"sum@{machine}@all@valid", str(sum(row[5] for row in out)))
        m.define(f"sum@{machine}@all@total", str(sum(row[6] for row in out)))
        m.define(f"sum@{machine}@all@slower", str(sum(row[7] for row in out)))
        m.define(f"sum@{machine}@all@cases", str(sum(row[8] for row in out)))
    return out


def summary_table(out, with_valid=True):
    cols = "lrrrrr" + ("r" if with_valid else "")
    head = ("Project & Re-sort today (ms) & Switch + page (ms) & Speed-up & Pre-sort, once (ms) & "
            "First click slower" + (" & Valid orders" if with_valid else "") + "\\\\")
    lines = ["\\begin{tabular}{" + cols + "}", "\\toprule", head, "\\midrule"]
    for label, resort, switch, ratio, presort, valid, total, slower, cases in out:
        cells = [label.replace("(on hold)", "").strip(), rng(resort), rng(switch),
                 rng([max(r, 1) for r in ratio], factor) + "$\\times$", rng(presort), f"{slower}/{cases}"]
        if with_valid:
            cells.append(f"{valid}/{total}")
        lines.append(" & ".join(cells) + "\\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def dolphin_details(m):
    """Partial sort, first-page cost and folder opening from the Dolphin benchmark."""
    data = rows(OUTPUTS / "bucketization_dolphin_stack.csv")
    if not data:
        return
    real = [r for r in data if r["dataset"] in ("node-modules-tree", "usr-tree", "linux-tree")]
    ratio = [float(r["partial_sort_ms"]) / float(r["keyed_switch_ms"]) for r in real]
    m.define("dol@partial@median", factor(statistics.median(ratio)))
    m.define("dol@partial@range", rng(ratio, factor))
    m.define("dol@partial@worst", num(max(float(r["partial_sort_ms"]) for r in real)))
    m.define("dol@cmp@presortratio", rng([float(r["cmp_presort_ms"]) / float(r["keyed_presort_ms"]) for r in real
                                          if float(r["cmp_presort_ms"]) > 0], factor))
    for r in data:
        m.define(f"dol@{r['dataset']}@{r['role']}@{r['order']}@resort", num(float(r["dolphin_resort_ms"])))
        m.define(f"dol@{r['dataset']}@{r['role']}@{r['order']}@switch", num(float(r["keyed_switch_ms"])))
        m.define(f"dol@{r['dataset']}@{r['role']}@{r['order']}@partial", num(float(r["partial_sort_ms"])))
        m.define(f"dol@{r['dataset']}@{r['role']}@{r['order']}@presort", num(float(r["keyed_presort_ms"])))
        m.define(f"dol@{r['dataset']}@{r['role']}@{r['order']}@fpc", r["first_page_cost"])
    opening = tables(OUTPUTS / "bucketization_dolphin_stack.csv")
    if len(opening) > 1:
        big = [r for r in opening[1] if r["dataset"] in ("node-modules-tree", "usr-tree", "linux-tree")]
        m.define("dol@open@dolphin", rng([float(r["dolphin_open_ms"]) for r in big]))
        m.define("dol@open@visible", rng([float(r["keyed_open_ms"]) for r in big]))
        m.define("dol@open@all", rng([float(r["keyed_open_all_keys_ms"]) for r in big]))
        m.define("dol@open@speedup", rng([float(r["dolphin_open_ms"]) / float(r["keyed_open_ms"]) for r in big],
                                         factor))
        m.define("dol@open@speedupall", rng([float(r["dolphin_open_ms"]) / float(r["keyed_open_all_keys_ms"])
                                             for r in big], factor))
    fpc = {}
    for r in data:
        fpc.setdefault(int(r["n"]), []).append(int(r["first_page_cost"]))
    for n, values in fpc.items():
        m.define(f"dol@fpc@{n}", rng(values, lambda v: f"{v:,}".replace(",", "{,}")))


def main():
    runner = load_runner()
    GEN.mkdir(parents=True, exist_ok=True)
    m = Macros()
    syn = {machine: synthetic(m, machine) for machine in MACHINES}
    (GEN / "table_synthetic.tex").write_text(synthetic_table(syn), encoding="utf-8")
    linux = summary(runner, m, "linux")
    (GEN / "table_projects_linux.tex").write_text(summary_table(linux), encoding="utf-8")
    runner = load_runner()  # fresh module: summary() tags the paths for the second machine
    windows = summary(runner, m, "windows")
    if windows:
        (GEN / "table_projects_windows.tex").write_text(summary_table(windows), encoding="utf-8")
    dolphin_details(m)
    (GEN / "numbers.tex").write_text(m.text(), encoding="utf-8")
    print(f"wrote {GEN}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
