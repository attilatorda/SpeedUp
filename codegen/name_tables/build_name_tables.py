#!/usr/bin/env python3
"""Builds name sort's character-frequency priors from US Census name data.

Inputs (public domain, US Census Bureau), downloaded once into `cache/`:
  - 2010 surnames: 162,253 surnames with counts (Names_2010Census.csv)
  - 1990 first names: female and male first names with frequencies

Outputs:
  - src/algorithms/sort/name_freq_tables.h: four tables of 257 symbols
    (0 = end of name, 1 + b = byte b), in parts per million:
      all       every character position, plus one end symbol per name
      pos[0..2] position 1, 2 and 3, over names that reach that position
  - benchmarks/datasets/names/{surnames,first-names}.tsv.gz: the name lists
    with weights, for capture_names.py

The mix is half surnames and half first names (a quarter female, a quarter
male), written in title case as people type them ("Smith", "Mary").

Usage:
    build_name_tables.py [--offline]    # --offline: fail instead of downloading
"""

import argparse
import csv
import gzip
import io
import sys
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CACHE = Path(__file__).resolve().parent / "cache"
HEADER_OUT = ROOT / "src" / "algorithms" / "sort" / "name_freq_tables.h"
DATA_OUT = ROOT / "benchmarks" / "datasets" / "names"

BASE = "https://www2.census.gov/topics/genealogy"
SOURCES = {
    "census_2010_surnames.zip": f"{BASE}/2010surnames/names.zip",
    "dist.female.first": f"{BASE}/1990surnames/dist.female.first",
    "dist.male.first": f"{BASE}/1990surnames/dist.male.first",
}

SYMBOLS = 257
PPM = 1_000_000
POSITIONS = 3


def fetch(offline):
    CACHE.mkdir(exist_ok=True)
    for name, url in SOURCES.items():
        path = CACHE / name
        if path.exists():
            continue
        if offline:
            sys.exit(f"missing {path} (run without --offline to download {url})")
        print(f"downloading {url}")
        with urllib.request.urlopen(url, timeout=120) as response:
            path.write_bytes(response.read())


def title_case(upper):
    out = []
    start = True
    for ch in upper:
        out.append(ch.upper() if start else ch.lower())
        start = not ch.isalpha()
    return "".join(out)


def read_surnames():
    with zipfile.ZipFile(CACHE / "census_2010_surnames.zip") as archive:
        text = archive.read("Names_2010Census.csv").decode("ascii")
    names = []
    for row in csv.DictReader(io.StringIO(text)):
        if row["name"] == "ALL OTHER NAMES" or not row["count"].isdigit():
            continue
        names.append((title_case(row["name"]), int(row["count"])))
    return names


def read_first_names(file_name):
    names = []
    for line in (CACHE / file_name).read_text(encoding="ascii").splitlines():
        parts = line.split()
        if len(parts) == 4:
            names.append((title_case(parts[0]), float(parts[1])))
    return names


def normalized(weighted):
    total = sum(weight for _, weight in weighted)
    return [(name, weight / total) for name, weight in weighted]


def tables(mix):
    """Counts per symbol for all positions and for positions 1..3."""
    every = [0.0] * SYMBOLS
    pos = [[0.0] * SYMBOLS for _ in range(POSITIONS)]
    for name, weight in mix:
        data = name.encode("utf-8")
        for b in data:
            every[1 + b] += weight
        every[0] += weight
        for k in range(POSITIONS):
            if len(data) > k:
                pos[k][1 + data[k]] += weight
            elif len(data) == k:
                pos[k][0] += weight
    return [to_ppm(every)] + [to_ppm(t) for t in pos]


def to_ppm(counts):
    """Largest-remainder rounding, so every table sums to exactly PPM."""
    total = sum(counts)
    exact = [c * PPM / total for c in counts]
    out = [int(x) for x in exact]
    order = sorted(range(SYMBOLS), key=lambda i: (-(exact[i] - out[i]), i))
    for i in order[: PPM - sum(out)]:
        out[i] += 1
    assert sum(out) == PPM
    return out


def c_array(values, indent="    "):
    lines = []
    for i in range(0, len(values), 12):
        lines.append(indent + ", ".join(f"{v:6d}" for v in values[i:i + 12]) + ",")
    return "\n".join(lines)


def write_header(all_table, pos_tables, counts):
    surnames, female, male = counts
    out = [
        "/* Generated by codegen/name_tables/build_name_tables.py. Do not edit. */",
        "/* Priors for name sort (name_sort.c): how often each byte occurs in",
        " * person names, in parts per million. Symbol 0 is the end of the name,",
        " * symbol 1 + b is byte b. Source: US Census Bureau (public domain),",
        f" * {surnames} surnames (2010) and {female} female and {male} male first",
        " * names (1990), mixed half surnames, half first names, in title case. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "#define SPEEDUP_NAME_SYMBOLS 257",
        "#define SPEEDUP_NAME_PRIOR_POSITIONS 3",
        "#define SPEEDUP_NAME_PRIOR_TOTAL 1000000u",
        "",
        "/* Every position, with one end symbol per name. */",
        "static const uint32_t speedup_name_prior_all[SPEEDUP_NAME_SYMBOLS] = {",
        c_array(all_table),
        "};",
        "",
        "/* Positions 1, 2 and 3, over the names at least that long (the end",
        " * symbol counts the names that end just before the position). */",
        "static const uint32_t speedup_name_prior_pos[SPEEDUP_NAME_PRIOR_POSITIONS][SPEEDUP_NAME_SYMBOLS] = {",
    ]
    for table in pos_tables:
        out += ["    {", c_array(table, "        "), "    },"]
    out += ["};", ""]
    HEADER_OUT.write_text("\n".join(out), encoding="ascii", newline="\n")
    print(f"wrote {HEADER_OUT.relative_to(ROOT)}")


def write_list(path, rows, fmt):
    DATA_OUT.mkdir(parents=True, exist_ok=True)
    text = "".join(f"{name}\t{fmt(weight)}\n" for name, weight in rows)
    # mtime=0 keeps the archive bytes identical from run to run
    with open(path, "wb") as raw, gzip.GzipFile(fileobj=raw, mode="wb", mtime=0, filename="") as out:
        out.write(text.encode("ascii"))
    print(f"wrote {path.relative_to(ROOT)} ({len(rows)} names)")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--offline", action="store_true", help="use only the cached downloads")
    args = parser.parse_args()
    fetch(args.offline)

    surnames = read_surnames()
    female = read_first_names("dist.female.first")
    male = read_first_names("dist.male.first")

    mix = ([(n, 0.5 * w) for n, w in normalized(surnames)] +
           [(n, 0.25 * w) for n, w in normalized(female)] +
           [(n, 0.25 * w) for n, w in normalized(male)])
    all_table, *pos_tables = tables(mix)
    write_header(all_table, pos_tables, (len(surnames), len(female), len(male)))

    write_list(DATA_OUT / "surnames.tsv.gz", surnames, lambda w: str(w))
    first = {}
    for name, weight in normalized(female) + normalized(male):
        first[name] = first.get(name, 0.0) + weight / 2
    write_list(DATA_OUT / "first-names.tsv.gz", sorted(first.items(), key=lambda kv: (-kv[1], kv[0])),
               lambda w: f"{w:.9f}")


if __name__ == "__main__":
    main()
